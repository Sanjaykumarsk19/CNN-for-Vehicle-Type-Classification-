# 5. CONVERT YOLO BOUNDING BOXES INTO CROPPED IMAGES
# ================================================================
#
# YOLO label format:
#
# class_id x_center y_center width height
#
# Coordinates are normalized between 0 and 1.
#
# We convert them into pixel coordinates and crop each vehicle.
# ================================================================

def create_crops(split):

    image_folder = os.path.join(VEHICLE_PATH, split, "images")
    label_folder = os.path.join(VEHICLE_PATH, split, "labels")

    output_folder = os.path.join(CROP_DATASET, split)

    image_files = [
        f for f in os.listdir(image_folder)
        if f.lower().endswith((".jpg", ".jpeg", ".png"))
    ]

    crop_count = 0
    skipped_count = 0

    print(f"\nProcessing {split} dataset...")
    print("Number of images:", len(image_files))

    for image_file in image_files:

        image_path = os.path.join(image_folder, image_file)

        # Corresponding label file
        label_file = os.path.splitext(image_file)[0] + ".txt"
        label_path = os.path.join(label_folder, label_file)

        # If label doesn't exist, skip image
        if not os.path.exists(label_path):
            skipped_count += 1
            continue

        # Read image
        image = cv2.imread(image_path)

        if image is None:
            skipped_count += 1
            continue

        height, width = image.shape[:2]

        # Read YOLO labels
        with open(label_path, "r") as f:
            labels = f.readlines()

        for object_number, line in enumerate(labels):

            values = line.strip().split()

            # YOLO should have 5 values
            if len(values) < 5:
                continue

            try:
                class_id = int(float(values[0]))

                x_center = float(values[1])
                y_center = float(values[2])
                box_width = float(values[3])
                box_height = float(values[4])

            except:
                continue

            # Make sure class ID is valid
            if class_id < 0 or class_id >= NUM_CLASSES:
                continue

            # Convert normalized coordinates to pixels
            x_center_pixel = int(x_center * width)
            y_center_pixel = int(y_center * height)

            box_width_pixel = int(box_width * width)
            box_height_pixel = int(box_height * height)

            # Calculate bounding box
            x1 = int(x_center_pixel - box_width_pixel / 2)
            y1 = int(y_center_pixel - box_height_pixel / 2)

            x2 = int(x_center_pixel + box_width_pixel / 2)
            y2 = int(y_center_pixel + box_height_pixel / 2)

            # Keep coordinates inside image
            x1 = max(0, x1)
            y1 = max(0, y1)

            x2 = min(width, x2)
            y2 = min(height, y2)

            # Check bounding box
            if x2 <= x1 or y2 <= y1:
                continue

            # Crop vehicle
            crop = image[y1:y2, x1:x2]

            if crop.size == 0:
                continue

            # Get class name
            class_name = str(class_names[class_id])

            # Create unique filename
            base_name = os.path.splitext(image_file)[0]

            crop_filename = (
                f"{base_name}_vehicle_{object_number}.jpg"
            )

            save_path = os.path.join(
                output_folder,
                class_name,
                crop_filename
            )

            # Save crop
            cv2.imwrite(save_path, crop)

            crop_count += 1

    print("Cropped vehicle images:", crop_count)
    print("Skipped images:", skipped_count)


# Create crops
